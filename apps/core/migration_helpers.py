"""Data-preserving key conversion for the locked-schema repair migrations."""
def convert_key(apps, schema_editor, app_label, model_name, columns, reverse=False):
    model = apps.get_model(app_label, model_name)
    table = schema_editor.quote_name(model._meta.db_table)
    quote = schema_editor.quote_name
    if schema_editor.connection.vendor == 'postgresql':
        with schema_editor.connection.cursor() as cursor:
            constraints = schema_editor.connection.introspection.get_constraints(cursor, model._meta.db_table)
        for name, detail in constraints.items():
            if detail['primary_key']:
                schema_editor.execute(f'ALTER TABLE {table} DROP CONSTRAINT {quote(name)}')
        if reverse:
            schema_editor.execute(f'ALTER TABLE {table} ADD COLUMN id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
        else:
            schema_editor.execute(f'ALTER TABLE {table} DROP COLUMN id')
            schema_editor.execute(f'ALTER TABLE {table} ADD PRIMARY KEY ({", ".join(map(quote, columns))})')
    elif schema_editor.connection.vendor == 'sqlite':
        fields = [f for f in model._meta.local_concrete_fields if f.column != 'id']
        definitions = []
        if reverse:
            definitions.append('id integer NOT NULL PRIMARY KEY AUTOINCREMENT')
        for field in fields:
            sql, params = schema_editor.column_sql(model, field)
            if params:
                raise RuntimeError('Unexpected parameterized column in key conversion')
            definitions.append(f'{quote(field.column)} {sql}')
            if field.is_relation:
                remote = field.remote_field.model._meta
                definitions[-1] += f' REFERENCES {quote(remote.db_table)} ({quote(remote.pk.column)}) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED'
        if not reverse:
            definitions.append(f'PRIMARY KEY ({", ".join(map(quote, columns))})')
        # No table references either composite-key table; all business values copy intact.
        temporary = quote(model._meta.db_table + '_key_repair')
        schema_editor.execute(f'CREATE TABLE {temporary} ({", ".join(definitions)})')
        names = ', '.join(quote(f.column) for f in fields)
        schema_editor.execute(f'INSERT INTO {temporary} ({names}) SELECT {names} FROM {table}')
        schema_editor.execute(f'DROP TABLE {table}')
        schema_editor.execute(f'ALTER TABLE {temporary} RENAME TO {table}')
    else:
        raise RuntimeError('Schema repair supports PostgreSQL and SQLite only')
